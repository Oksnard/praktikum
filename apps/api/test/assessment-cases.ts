export function authoredAssignment(f: (typeof assessmentCases)[number]) {
  return AssignmentV2Schema.parse({
    version: 2,
    summary: f.source,
    question: f.question,
    evidence: [f.requirements[0][2]],
    assessment: f.requirements.map(
      ([criterion, requirement, source_quote], i) => ({
        id: `r${i + 1}`,
        criterion,
        requirement,
        source_quote,
        question_quote: f.question,
      }),
    ),
  });
}
export function authoredEvaluation(f: (typeof assessmentCases)[number]) {
  return {
    version: 2,
    assessment_mode: "snapshot",
    score: 100,
    criteria: criteria.map((c) => ({
      id: c.id,
      score: c.max,
      explanation: "Требование выполнено; допустима смысловая перефразировка.",
    })),
    evidence: f.requirements.map((r) => r[2]),
    unsupported_claims: [],
    gaps: [],
    feedback: "План соблюдает применимые требования.",
    recommendations: ["Сохраняйте этот порядок действий."],
    personal_material: f.source,
    checks: f.quotes.map((quote, i) => ({
      rule_id: `r${i + 1}`,
      status: "met",
      answer_quotes: [quote],
      explanation: "Цитата подтверждает требуемое действие.",
    })),
  };
}
